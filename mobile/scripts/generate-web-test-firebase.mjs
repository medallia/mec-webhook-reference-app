#!/usr/bin/env node
/**
 * Generates web-test Firebase files from EXPO_PUBLIC_FIREBASE_* environment variables.
 *
 * Usage:
 *   cd mobile && node scripts/generate-web-test-firebase.mjs
 *   # or with .env loaded:
 *   set -a && source .env && set +a && node scripts/generate-web-test-firebase.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(__dirname, "..");
const webTestDir = path.join(mobileRoot, "web-test");

const FIREBASE_ENV_KEYS = [
  "EXPO_PUBLIC_FIREBASE_API_KEY",
  "EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN",
  "EXPO_PUBLIC_FIREBASE_PROJECT_ID",
  "EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET",
  "EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  "EXPO_PUBLIC_FIREBASE_APP_ID",
  "EXPO_PUBLIC_FIREBASE_VAPID_KEY",
];

function loadEnvFile(envPath) {
  if (!fs.existsSync(envPath)) {
    return;
  }

  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separator = trimmed.indexOf("=");
    if (separator === -1) {
      continue;
    }

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

function required(name) {
  const value = process.env[name]?.trim();
  if (!value) {
    console.error(`error: missing required environment variable: ${name}`);
    process.exit(1);
  }
  return value;
}

function buildFirebaseConfig() {
  return {
    apiKey: required("EXPO_PUBLIC_FIREBASE_API_KEY"),
    authDomain: required("EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN"),
    projectId: required("EXPO_PUBLIC_FIREBASE_PROJECT_ID"),
    storageBucket: required("EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET"),
    messagingSenderId: required("EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID"),
    appId: required("EXPO_PUBLIC_FIREBASE_APP_ID"),
  };
}

function writeGeneratedFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents, "utf8");
}

loadEnvFile(path.join(mobileRoot, ".env"));

const missing = FIREBASE_ENV_KEYS.filter((key) => !process.env[key]?.trim());
if (missing.length > 0) {
  console.error("error: missing Firebase web-test environment variables:");
  for (const key of missing) {
    console.error(`  - ${key}`);
  }
  console.error("");
  console.error("Add them to mobile/.env (see mobile/.env.example) and re-run.");
  process.exit(1);
}

const firebaseConfig = buildFirebaseConfig();
const vapidKey = required("EXPO_PUBLIC_FIREBASE_VAPID_KEY");
const generatedBanner =
  "// Generated by scripts/generate-web-test-firebase.mjs — do not edit.\n";

const configJs = `${generatedBanner}
export const firebaseConfig = ${JSON.stringify(firebaseConfig, null, 2)};

export const VAPID_KEY = ${JSON.stringify(vapidKey)};
`;

const serviceWorkerJs = `${generatedBanner}
importScripts("https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(firebaseConfig, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const data = payload.data || {};
  const title = payload.notification?.title || data.title || "Survey Invitation";
  const body = payload.notification?.body || data.body || "Tap to share your feedback.";

  self.registration.showNotification(title, {
    body,
    icon: "/favicon.ico",
    data: {
      messageId: data.messageId,
      surveyUrl: data.surveyUrl,
    },
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const surveyUrl = event.notification.data?.surveyUrl;
  if (surveyUrl) {
    event.waitUntil(clients.openWindow(surveyUrl));
  }
});
`;

writeGeneratedFile(path.join(webTestDir, "firebase-config.js"), configJs);
writeGeneratedFile(path.join(webTestDir, "firebase-messaging-sw.js"), serviceWorkerJs);

console.log("Generated:");
console.log(`  ${path.relative(mobileRoot, path.join(webTestDir, "firebase-config.js"))}`);
console.log(`  ${path.relative(mobileRoot, path.join(webTestDir, "firebase-messaging-sw.js"))}`);
